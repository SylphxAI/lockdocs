#!/usr/bin/env python3
"""Regenerate/check the Latin face after npm ci, from any working directory.
Offline tooling: Python 3.11, fonttools==4.60.1, brotli==1.1.0.
Run python3 apps/web/scripts/jetbrains-mono.py [--check].
"""

import argparse
from hashlib import sha256
from io import BytesIO
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont


web = Path(__file__).resolve().parents[1]
package = web / "node_modules/@fontsource-variable/jetbrains-mono"
latin = "jetbrains-mono-latin-wght-normal.woff2"
source = (package / "files" / latin).read_bytes()
# Fontsource 5.3.0 / Google Fonts v24 (the existing lockfile's Latin face).
if sha256(source).hexdigest() != "18be452724bfdc236c074ca94a249a7f41a86752c7d04ab258ce9ed5651f6a7e":
    raise SystemExit("JetBrains Mono source changed; recheck coverage, weights and browser parity")

before = TTFont(BytesIO(source), recalcTimestamp=False)
# 400 is our lightest mono text today. Keep the entire default-to-bold
# side of the Latin axis (including 800); other subsets are unchanged.
minimum, maximum = 400, 800
font = instantiateVariableFont(before, {"wght": (minimum, maximum)})
output = BytesIO()
font.save(output)
encoded = output.getvalue()
after = TTFont(BytesIO(encoded))
if before.getTableData("cmap") != after.getTableData("cmap") or before.getGlyphOrder() != after.getGlyphOrder():
    raise SystemExit("JetBrains Mono Latin glyph coverage changed")
if len(encoded) * 5 > len(source) * 4:
    raise SystemExit("JetBrains Mono Latin must be at least 20% smaller")

# Separate weight descriptors would stop these subsets acting as one face in
# browsers. Keep the upstream descriptors verbatim; only the Latin binary
# clamps weights below 400, which the browser regression forbids in app text.
css = (package / "index.css").read_text(encoding="utf-8").replace(
    "url(./files/", "url(@fontsource-variable/jetbrains-mono/files/"
)
css = css.replace(f"url(@fontsource-variable/jetbrains-mono/files/{latin})", f"url(./{latin})")
css = f"/* Generated by scripts/jetbrains-mono.py; do not edit. */\n{css.rstrip()}\n"

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="verify the committed outputs without writing")
check = parser.parse_args().check
for path, data in {
    web / "src/fonts" / latin: encoded,
    web / "src/fonts/jetbrains-mono.css": css.encode(),
    web / "public/fonts/jetbrains-mono-OFL.txt": (package / "LICENSE").read_bytes(),
}.items():
    if check:
        if not path.exists() or path.read_bytes() != data:
            raise SystemExit(f"Generated output differs: {path.relative_to(web)}")
    else:
        path.write_bytes(data)
